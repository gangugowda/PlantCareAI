function makeEvents(): WateringEvent[] {
  const events: WateringEvent[] = []
  const patterns = [
    { plantId: 'plant-monstera', days: [2, 5, 9, 13, 18, 23, 28], sec: 12 },
    { plantId: 'plant-snake', days: [9, 19, 29], sec: 8 },
    { plantId: 'plant-aloe', days: [14, 27], sec: 7 },
    { plantId: 'plant-money', days: [4, 8, 12, 17, 21, 26], sec: 10 },
    { plantId: 'plant-peace', days: [1, 4, 7, 10, 14, 18, 22, 27], sec: 9 },
  ]
  patterns.forEach((pattern) => {
    pattern.days.forEach((offset, index) => {
      events.push({
        id: `water-${pattern.plantId}-${offset}`,
        plantId: pattern.plantId,
        date: iso(offset),
        durationSec: pattern.sec,
        liters: Number((pattern.sec * 0.028 + (index % 3) * 0.012).toFixed(2)),
        mode: index % 4 === 0 ? 'manual' : 'auto',
        status: 'completed',
      })
    })
  })
  return events.sort((a, b) => b.date.localeCompare(a.date))
}

